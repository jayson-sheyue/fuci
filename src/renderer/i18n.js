let active = 'zh';

function normalizeLocale(value) {
  const text = String(value || '').toLowerCase();
  if (text === 'ja' || text.startsWith('ja-')) return 'ja';
  if (text === 'en' || text.startsWith('en-')) return 'en';
  return 'zh';
}

function setLocale(value) {
  active = normalizeLocale(value);
  return active;
}

function getLocale() {
  return active;
}

function t(locale, key, vars) {
  const lang = normalizeLocale(locale);
  const template = catalogs[lang][key] ?? catalogs.zh[key] ?? key;
  if (!vars) return template;
  return template.replace(/\{(\w+)\}/g, (_, name) => (vars[name] == null ? '' : String(vars[name])));
}

function tr(key, vars) {
  return t(active, key, vars);
}

const api = {
  LOCALES,
  catalogs,
  normalizeLocale,
  setLocale,
  getLocale,
  t,
  tr,
};

if (typeof module === 'object' && module.exports) module.exports = api;
else globalThis.fuciI18n = api;
